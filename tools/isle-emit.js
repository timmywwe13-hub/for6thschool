function chunkRows(str, perLine, cols) {
  const out = [];
  for (let i = 0; i < str.length; i += cols) out.push(str.slice(i, i + cols));
  const lines = [];
  for (let i = 0; i < out.length; i += perLine) {
    lines.push('  ' + out.slice(i, i + perLine).map(function (s) { return "'" + s + "'"; }).join(',\n  '));
  }
  return lines.join(',\n');
}
function num(v, dp) { return v.toFixed(dp === undefined ? 1 : dp); }

function build() {
  const t = JSON.parse(fs.readFileSync(JSON_IN, 'utf8'));
  const L = [];
  L.push('/* =====================================================================');
  L.push('   ISLE ROYALE - the island traced off the reference map picture.');
  L.push('   GENERATED by tools/isle-emit.js from tools/isle-trace.json; re-run');
  L.push('   those two if the picture ever changes. Every position below is in');
  L.push('   MAP-PICTURE PIXELS so it can be read straight off the art: ISLE_ART');
  L.push('   is the calibration that turns a pixel into a world unit.');
  L.push('   ===================================================================== */');
  L.push('const ISLE_ART = {');
  L.push("  file: 'isle_map.png', base64File: 'isle_map.png.js', base64Global: 'ISLE_MAP_B64',");
  L.push('  k: ' + t.scale.k + ',              // world units per picture pixel');
  L.push('  cx: ' + t.mainland.px + ', cy: ' + t.mainland.py +
    ',   // the island centre in the picture = world (0,0)');
  L.push('  w: ' + t.image.w + ', h: ' + t.image.h + ',           // the picture itself');
  L.push("  sea: 'rgb(" + t.image.sea.r + ',' + t.image.sea.g + ',' + t.image.sea.b +
    ")'  // its ocean, to ring the art with");
  L.push('};');
  L.push('/* coastline: bearing (radians, 0 = east, turning towards +z south) -> how');
  L.push('   far the coast is from the centre, in picture pixels. 48 samples. */');
  L.push('const ISLE_SHORE = [');
  const shore = [];
  for (let i = 0; i < t.shore.length; i += 4) {
    shore.push('  ' + t.shore.slice(i, i + 4).map(function (s) {
      return '[' + s[0].toFixed(4) + ', ' + num(s[1]) + ']';
    }).join(', '));
  }
  L.push(shore.join(',\n'));
  L.push('];');
  L.push('/* inland water, on a 64 x 64 lattice over the picture.');
  L.push('   DEPTH  = how deep the carve runs: 0 on dry land, 9 the deepest lake.');
  L.push('            This is what cuts the lakes and rivers out of the land.');
  L.push('   VALLEY = how close the nearest water is: 9 on the bank, 0 far away.');
  L.push('            This is what dips the land down towards the water.');
  L.push('   One string per lattice row, so the reader can index rows[j] directly:');
  L.push('   keep it that way if you reshape these - the game reads charCodeAt(i). */');
  L.push('const ISLE_DEPTH = [');
  L.push(chunkRows(t.depth, 1, 64));
  L.push('];');
  L.push('const ISLE_VALLEY = [');
  L.push(chunkRows(t.valley, 1, 64));
  L.push('];');
  L.push('/* surface, on a 48 x 48 lattice: 0 green, 1 sand, 2 snow. Read with');
  L.push('   bilinear filtering and blended, so the biome borders come out soft.');
  L.push('   One string per lattice row, same as the two grids above. */');
  L.push('const ISLE_BIOME = [');
  L.push(chunkRows(t.biome, 1, 48));
  L.push('];');
  L.push('/* the little islands the picture draws off the coast: centre in picture');
  L.push('   pixels and the radius to raise them over. */');
  L.push('const ISLE_ISLETS = [');
  const isl = [];
  for (let i = 0; i < t.islets.length; i += 4) {
    isl.push('  ' + t.islets.slice(i, i + 4).map(function (s) {
      return '{ x: ' + s.px + ', z: ' + s.py + ', r: ' + s.r + ' }';
    }).join(', '));
  }
  L.push(isl.join(',\n'));
  L.push('];');
  L.push('/* the POIs: picture pixels, the pad flattened under each one, and `city`');
  L.push('   for the single dense downtown. The height is taken from the terrain. */');
  L.push('const ISLE_SITES = [');
  L.push(SITES.map(function (s) {
    return '  { name: ' + JSON.stringify(s.name) + ', x: ' + s.x + ', z: ' + s.z +
      ', pad: ' + s.pad + ', y: null' + (s.city ? ', city: true' : '') + ' }';
  }).join(',\n'));
  L.push('];');
  L.push('/* the road network, as polylines of picture pixels. The terrain is the');
  L.push('   authority on where the water is, so the game resamples these and walks');
  L.push('   them onto dry ground when it builds the world (relaxRoadsToLand). */');
  L.push('const ISLE_ROADS = [');
  L.push(ROADS.map(function (r) {
    return '  [' + r.map(function (p) { return '[' + p[0] + ', ' + p[1] + ']'; }).join(', ') + ']';
  }).join(',\n'));
  L.push('];');
  return L.join('\r\n') + '\r\n';
}

function main() {
  const args = process.argv.slice(2);
  const block = build();
  fs.writeFileSync(OUT_TXT, block, 'utf8');
  const idx = args.indexOf('--insert');
  if (idx < 0) {
    process.stdout.write(block);
    console.error('\nwrote ' + OUT_TXT + ' (' + block.length + ' chars)');
    return;
  }
  const target = path.resolve(args[idx + 1] || 'index.html');
  const html = fs.readFileSync(target, 'utf8');
  const A = '/* ==== ISLE DATA START ==== */';
  const B = '/* ==== ISLE DATA END ==== */';
  const a = html.indexOf(A), b = html.indexOf(B);
  if (a < 0 || b < 0 || b < a) throw new Error('the ISLE DATA markers are not in ' + target);
  /* the markers stay in the file - that is what makes the splice re-runnable.
     build() already ends with CRLF, so each marker keeps its own line. */
  const merged = html.slice(0, a) + A + '\r\n' + block + B + html.slice(b + B.length);
  /* the file is UTF-8 with no BOM and CRLF line endings - keep it that way */
  fs.writeFileSync(target, merged, 'utf8');
  console.log('spliced ' + block.length + ' chars into ' + target +
    ' (' + Buffer.byteLength(html, 'utf8') + ' -> ' + Buffer.byteLength(merged, 'utf8') + ' bytes)');
}

if (require.main === module) main();
module.exports = { build, SITES, ROADS };
