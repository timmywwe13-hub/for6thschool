// isle-emit.js - turn tools/isle-trace.json into the data block that lives in
// index.html, and (with --insert) splice it in between the ISLE DATA markers.
//
//   node tools/isle-emit.js                  -> prints the block, writes tools/isle-data.js.txt
//   node tools/isle-emit.js --insert index.html
//
// The POIs and the road network below are the one editorial layer on top of the
// trace: everything is written in MAP-PICTURE PIXELS so it can be read straight
// off the art (ISLE_ART in index.html says how a pixel becomes a world unit).
